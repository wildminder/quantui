#!/usr/bin/env bash
# Install the local commit-time gate hook.
#
# The repository now has a remote and CI (.github/workflows/ci.yml) runs the
# same gates on every push. This hook is the local mirror of that gate, so a
# contributor catches a failure before pushing rather than after. The generated
# hook runs scripts/precommit_ruff.sh (ruff + mypy + optional coverage) and then
# scripts/gate_tests.sh (pytest), blocking the commit on the first failure.
#
# Usage:   bash scripts/install_hooks.sh [REPO_ROOT]
# Default REPO_ROOT is `git rev-parse --show-toplevel`.
# Idempotent: a second run rewrites the hook byte-identically.
# Emergency bypass for a single commit: git commit --no-verify.
set -euo pipefail

root="${1:-$(git rev-parse --show-toplevel)}"

if [ ! -d "$root/.git" ]; then
  echo "install_hooks: not a git repo: $root" >&2
  exit 1
fi

mkdir -p "$root/.git/hooks"
hook="$root/.git/hooks/pre-commit"

cat > "$hook" <<'HOOK'
#!/bin/sh
# quantui gate hook - GENERATED by scripts/install_hooks.sh.
# Edit the installer and re-run it; manual edits here are overwritten.
# Emergency bypass: git commit --no-verify.
root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
cd "$root" || exit 1

bash scripts/precommit_ruff.sh
rc=$?
if [ "$rc" -ne 0 ]; then
  echo "pre-commit: FAIL - ruff/mypy gate failed (scripts/precommit_ruff.sh)" >&2
  exit "$rc"
fi

bash scripts/gate_tests.sh
rc=$?
if [ "$rc" -ne 0 ]; then
  echo "pre-commit: FAIL - pytest gate failed (scripts/gate_tests.sh)" >&2
  exit "$rc"
fi

echo "pre-commit: gate OK"
HOOK

chmod +x "$hook"
echo "install_hooks: installed $hook"
